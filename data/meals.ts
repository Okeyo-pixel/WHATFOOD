/**
 * Dynamically filters the meal catalog by selected budget ceiling and Glovo category bubble.
 */
export function filterMeals(
  meals: Meal[],
  maxBudgetKes: number,
  activeCategory: FilterCategoryId
): Meal[] {
  return meals.filter((meal) => {
    if (meal.totalCostKes > maxBudgetKes) return false;

    switch (activeCategory) {
      case 'all':
        return true;
      case 'kienyeji':
        return meal.isKienyeji;
      case 'under350':
        return meal.totalCostKes <= 350;
      default:
        return meal.category === activeCategory;
    }
  });
}